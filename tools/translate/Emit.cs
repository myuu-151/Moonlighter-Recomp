using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace MoonlighterTranslate;

// Writes the translation (docs/translator_plan.md, "Output"):
//   game.h        every translated type: forward declarations, enums, then the classes,
//                 structs and interfaces in dependency order (bases and value fields first), then
//                 the bodies of generic types and methods (templates);
//   <file>.cpp    the bodies of the methods declared in that C# file, its static fields;
//   sources.cmake the .cpp files, for recomp/CMakeLists.txt;
//   report.tsv    every method: translated, or why not (an unsupported construct, missing bindings).
public sealed class Emitter
{
    readonly Translator tr;
    readonly Names N;
    readonly string outDir;

    public Emitter(Translator tr, string outDir)
    {
        this.tr = tr;
        N = tr.N;
        this.outDir = outDir;
    }

    sealed class TypeOut
    {
        public INamedTypeSymbol T;
        public string File; // the C# file it comes from
        public List<IMethodSymbol> Methods = new();
        public List<IFieldSymbol> Fields = new();
        public List<IFieldSymbol> StaticFields = new();
        public List<IEventSymbol> Events = new();
        public bool Generic;
        // The static fields the collector traces as roots: references and structs, and the
        // delegates of static field-like events (a subscriber's handler is held only there).
        public bool HasTracedStatics => StaticFields.Any(f => NeedsTrace(f.Type)) || Events.Any(e => e.IsStatic);
    }

    public void Write()
    {
        Directory.CreateDirectory(outDir);
        var outs = new Dictionary<INamedTypeSymbol, TypeOut>(SymbolEqualityComparer.Default);
        foreach (var t in tr.Types) outs[t] = Collect(t);

        // ---- game.h ----
        var h = new StringBuilder();
        h.Append("// Generated by tools/translate from the game's Assembly-CSharp.dll: do not edit, do not commit.\n");
        h.Append("#pragma once\n\n#include \"cs/Runtime.h\"\n");
        foreach (var inc in tr.Includes.OrderBy(x => x, StringComparer.Ordinal)) h.Append($"#include \"{inc}\"\n");
        h.Append('\n');

        // forward declarations and enums
        var ordered = Order(outs.Values.ToList());
        foreach (var o in ordered.Where(o => o.T.TypeKind == TypeKind.Enum)) h.Append(Namespaced(o.T, EnumDecl(o.T)));
        foreach (var o in ordered.Where(o => o.T.TypeKind is TypeKind.Class or TypeKind.Struct or TypeKind.Interface))
            h.Append(Namespaced(o.T, Template(o.T) + (o.T.TypeKind == TypeKind.Interface || o.T.TypeKind == TypeKind.Struct ? "struct " : "class ") + N.FlatName(o.T) + ";\n"));
        h.Append('\n');

        var cpp = new Dictionary<string, StringBuilder>(StringComparer.Ordinal);
        StringBuilder Cpp(string file)
        {
            if (!cpp.TryGetValue(file, out var sb))
            {
                cpp[file] = sb = new StringBuilder();
                sb.Append("// Generated by tools/translate from the game's ").Append(file).Append(": do not edit, do not commit.\n");
                sb.Append("#include \"game.h\"\n\n");
            }
            return sb;
        }
        var templates = new StringBuilder();

        foreach (var o in ordered)
        {
            if (o.T.TypeKind == TypeKind.Enum) continue;
            h.Append(Namespaced(o.T, ClassDecl(o)));
            var defs = o.Generic ? templates : Cpp(o.File);
            Definitions(o, defs, templates);
        }
        h.Append("\n// ---- generic types and methods ----\n\n").Append(templates);

        // AddComponent by the script's name (a prefab's MonoBehaviours, bind's prefab builder).
        var scripts = ordered.Select(o => o.T).Where(t => t.TypeKind == TypeKind.Class && !t.IsAbstract && !t.IsGenericType &&
                                                          !t.Name.StartsWith("_003C", StringComparison.Ordinal) && DerivesFrom(t, "UnityEngine.MonoBehaviour") &&
                                                          EngineBaseMapped(t) && HasDefaultCtor(t)).ToList();
        if (scripts.Count > 0)
        {
            h.Append("\nnamespace gen {\n// The translated MonoBehaviour named `name` (its class name, or its full name) added to `go`; nullptr if none.\n");
            h.Append("::UnityEngine::Component* cs_AddComponent(::UnityEngine::GameObject* go, const char* name);\n}\n");
            var sc = Cpp("components.cs");
            sc.Append("#include <cstring>\n\nnamespace gen {\n::UnityEngine::Component* cs_AddComponent(::UnityEngine::GameObject* go, const char* name) {\n");
            foreach (var t in scripts)
            {
                string full = t.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat).Replace("global::", "");
                string cond = $"!::std::strcmp(name, \"{t.Name}\")" + (full != t.Name ? $" || !::std::strcmp(name, \"{full}\")" : "");
                sc.Append($"    if ({cond}) return ::cs::nc(go)->AddComponent<{N.Ref(t)}>();\n");
            }
            sc.Append("    return nullptr;\n}\n} // namespace gen\n");
        }

        File.WriteAllText(Path.Combine(outDir, "game.h"), h.ToString(), new UTF8Encoding(false));
        var written = new List<string>();
        foreach (var (file, sb) in cpp.OrderBy(kv => kv.Key, StringComparer.Ordinal))
        {
            string name = file.Replace('/', '_').Replace('\\', '_').Replace(".cs", ".cpp");
            File.WriteAllText(Path.Combine(outDir, name), sb.ToString(), new UTF8Encoding(false));
            written.Add(name);
        }
        // Old files of a previous translation would still be listed by a glob: only the list counts.
        var cm = new StringBuilder("# Generated by tools/translate: the translated game sources.\nset(ML_GEN_SOURCES\n");
        foreach (var w in written) cm.Append("    ${ML_GEN_DIR}/").Append(w).Append('\n');
        cm.Append(")\n");
        File.WriteAllText(Path.Combine(outDir, "sources.cmake"), cm.ToString(), new UTF8Encoding(false));
        WriteReport();
    }

    // ---- collecting a type's members -------------------------------------------------------------------

    TypeOut Collect(INamedTypeSymbol t)
    {
        var o = new TypeOut { T = t, File = FileOf(t), Generic = Names.AllTypeParameters(t).Count > 0 };
        foreach (var m in t.GetMembers())
        {
            switch (m)
            {
                case IMethodSymbol ms when tr.Methods.ContainsKey(ms):
                    o.Methods.Add(ms);
                    break;
                case IFieldSymbol f when !f.IsConst:
                    bool used = tr.IsFieldUsed(f) || tr.IsFull(t) && f.AssociatedSymbol == null;
                    // an auto-property's backing field comes with its accessors
                    if (f.AssociatedSymbol is IPropertySymbol p && (p.GetMethod != null && tr.Methods.ContainsKey(p.GetMethod) || p.SetMethod != null && tr.Methods.ContainsKey(p.SetMethod))) used = true;
                    if (f.AssociatedSymbol is IEventSymbol) used = false; // events emit their own field
                    if (!used) break;
                    if (f.IsStatic) o.StaticFields.Add(f);
                    else o.Fields.Add(f);
                    break;
                case IEventSymbol e when tr.IsEventUsed(e) || tr.IsFull(t) || e.AddMethod != null && tr.Methods.ContainsKey(e.AddMethod) || e.RemoveMethod != null && tr.Methods.ContainsKey(e.RemoveMethod):
                    if (tr.IsFieldLikeEvent(e)) o.Events.Add(e);
                    break;
            }
        }
        // the implicit static constructor of static field initializers
        return o;
    }

    string FileOf(INamedTypeSymbol t)
    {
        var r = t.DeclaringSyntaxReferences.FirstOrDefault();
        if (r == null) return "unknown.cs";
        return Path.GetRelativePath(tr.GC.DecompDir, r.SyntaxTree.FilePath).Replace('\\', '/');
    }

    // Bases, interfaces and value fields before the types that need them complete.
    List<TypeOut> Order(List<TypeOut> all)
    {
        var byType = all.ToDictionary(o => o.T, o => o, SymbolEqualityComparer.Default);
        var result = new List<TypeOut>();
        var state = new Dictionary<INamedTypeSymbol, int>(SymbolEqualityComparer.Default);
        void Visit(TypeOut o)
        {
            if (state.TryGetValue(o.T, out int s))
            {
                if (s == 1) throw new TranslateException($"cyclic value types at {o.T}");
                return;
            }
            state[o.T] = 1;
            foreach (var d in Deps(o))
                if (byType.TryGetValue(d.OriginalDefinition, out var od)) Visit(od);
            state[o.T] = 2;
            result.Add(o);
        }
        foreach (var o in all.OrderBy(o => N.QualifiedGameName(o.T), StringComparer.Ordinal)) Visit(o);
        return result;
    }

    IEnumerable<INamedTypeSymbol> Deps(TypeOut o)
    {
        var t = o.T;
        if (t.BaseType != null) yield return t.BaseType;
        foreach (var i in t.Interfaces) yield return i;
        foreach (var f in o.Fields)
            foreach (var d in ValueDeps(f.Type)) yield return d;
        foreach (var m in o.Methods)
        {
            // inline accessors use their field's type
        }
    }

    IEnumerable<INamedTypeSymbol> ValueDeps(ITypeSymbol t)
    {
        if (t is INamedTypeSymbol nt && t.IsValueType)
        {
            yield return nt;
            foreach (var a in nt.TypeArguments)
                foreach (var d in ValueDeps(a)) yield return d;
        }
    }

    // ---- declarations -----------------------------------------------------------------------------------

    string Namespaced(INamedTypeSymbol t, string body)
    {
        string ns = Names.NamespacePath(t);
        string open = "namespace gen {" + (ns.Length > 0 ? string.Concat(ns.Split("::").Select(p => $" namespace {p} {{")) : "") + "\n";
        string close = "}" + (ns.Length > 0 ? new string('}', ns.Split("::").Length) : "") + "\n\n";
        return open + body + close;
    }

    string Template(INamedTypeSymbol t)
    {
        var tps = Names.AllTypeParameters(t);
        return tps.Count == 0 ? "" : "template <" + string.Join(", ", tps.Select(p => "typename " + N.TypeParam(p))) + "> ";
    }

    string EnumDecl(INamedTypeSymbol t)
    {
        var sb = new StringBuilder();
        string u = N.Type(t.EnumUnderlyingType);
        sb.Append($"enum class {N.FlatName(t)} : {u} {{\n");
        foreach (var f in t.GetMembers().OfType<IFieldSymbol>().Where(f => f.HasConstantValue))
            sb.Append($"    {Names.Ident(f.Name)} = {Names.Literal(Convert.ChangeType(f.ConstantValue, f.ConstantValue.GetType()), t.EnumUnderlyingType)},\n");
        sb.Append("};\n");
        // boxing support: the name and ToString (Enum.ToString: the member's name, else the number)
        string full = Names.FullName(t);
        string cls = N.FlatName(t);
        sb.Append($"inline const char* cs_box_typename(const {cls}*) {{ return \"{full}\"; }}\n");
        sb.Append($"inline ::cs::String* cs_box_tostring({cls} v) {{\n    switch (static_cast<{u}>(v)) {{\n");
        var seen = new HashSet<object>();
        foreach (var f in t.GetMembers().OfType<IFieldSymbol>().Where(f => f.HasConstantValue))
            if (seen.Add(f.ConstantValue))
                sb.Append($"    case {Names.Literal(f.ConstantValue, t.EnumUnderlyingType)}: return {Names.StringLiteral(f.Name)};\n");
        sb.Append($"    default: return ::cs::ToString(static_cast<{(u is "int8_t" or "uint8_t" or "int16_t" or "uint16_t" ? "int32_t" : u)}>(v));\n    }}\n}}\n");
        return sb.ToString();
    }

    string ClassDecl(TypeOut o)
    {
        var t = o.T;
        var sb = new StringBuilder();
        sb.Append(Template(t));
        bool isInterface = t.TypeKind == TypeKind.Interface;
        bool isStruct = t.TypeKind == TypeKind.Struct;
        sb.Append(isInterface || isStruct ? "struct " : "class ").Append(N.FlatName(t));
        var bases = new List<string>();
        if (!isInterface && !isStruct)
        {
            var bt = t.BaseType;
            if (bt == null || bt.SpecialType == SpecialType.System_Object) bases.Add("public ::cs::Object");
            else bases.Add("public " + N.Type(bt));
        }
        foreach (var i in t.Interfaces)
        {
            if (!InterfaceMapped(i)) continue; // an unbound interface (a gap): not a base, its members plain methods
            string it = TryType(i);
            if (it != null) bases.Add("public virtual " + it);
        }
        if (bases.Count > 0) sb.Append(" : ").Append(string.Join(", ", bases));
        sb.Append(" {\npublic:\n");
        if (isInterface) sb.Append($"    virtual ~{N.FlatName(t)}() = default;\n");
        // Instantiate's copy (cs_Clone) runs the copy constructor: defined once, with the methods,
        // each class's copying its own fields and calling its base's, rather than the whole chain
        // inlined into every class's cs_Clone.
        if (OutOfLineCopy(t))
        {
            sb.Append($"    {N.FlatName(t)}() = default;\n");
            sb.Append($"    {N.FlatName(t)}(const {N.FlatName(t)}& o);\n");
            OutOfLine(t).Append($"{Template(t)}{N.QualifiedGameName(t)[2..]}{TemplateArgsOf(t)}::{N.FlatName(t)}(const {N.FlatName(t)}& o) = default;\n");
        }

        // fields
        foreach (var f in o.Fields)
            sb.Append($"    {TypeOrGap(f.Type)} {N.Field(f)}{{}};\n");
        foreach (var e in o.Events)
            sb.Append($"    {(e.IsStatic ? "static " : "")}{TypeOrGap(e.Type)} {Names.Ident(e.Name)}{(e.IsStatic ? "" : "{}")};\n");
        foreach (var f in o.StaticFields)
            sb.Append($"    static {TypeOrGap(f.Type)} {N.Field(f)};\n");

        // static initialization: __si() runs the static constructor once
        bool si = tr.StaticInitActive(t);
        // (a generic type's statics register as roots per instantiation, at its first static access:
        // Translator.NeedsSiCall)
        bool siGeneric = o.Generic && o.HasTracedStatics;
        if (si || siGeneric)
        {
            sb.Append("    static int8_t cs_cctor_state_;\n");
            sb.Append("    static void __si() {\n        if (cs_cctor_state_) return;\n        cs_cctor_state_ = 1;\n");
            if (siGeneric) sb.Append("        ::cs::RegisterRoots(&cs_trace_statics);\n");
            if (si) sb.Append("        ::cs::StaticScope heap_;\n        __cctor();\n");
            sb.Append("    }\n");
            if (si && !o.Methods.Any(m => m.MethodKind == MethodKind.StaticConstructor)) sb.Append("    static void __cctor();\n");
        }

        // name hiding: overloads of a base's methods stay visible
        var names = new HashSet<string>(StringComparer.Ordinal);
        foreach (var m in o.Methods)
            if (m.MethodKind == MethodKind.Ordinary && !m.IsStatic && t.BaseType != null && N.IsGame(t.BaseType)) names.Add(N.Method(m));
        foreach (var n in names.OrderBy(x => x, StringComparer.Ordinal))
            if (BaseHasMethodNamed(t.BaseType, n)) sb.Append($"    using {N.Type(t.BaseType)}::{n};\n");

        // methods
        foreach (var m in o.Methods)
        {
            var r = tr.Methods[m];
            sb.Append("    ").Append(MethodDecl(m, o, inClass: true)).Append('\n');
            // (units.txt's `wrap`: the game's body under its own name, the driver's around it)
            if (r.Wrap) sb.Append($"    {(m.IsStatic ? "static " : "")}{TypeOrGap(m.ReturnType)} {N.Method(m)}__game({Params(m)});\n");
        }

        // interface implementations that forward to the C# implementing member
        if (!isInterface) sb.Append(Forwarders(t));
        // Unity's side of a MonoBehaviour: its messages, SendMessage / Invoke by name, the
        // serialized fields a prefab sets.
        if (!isInterface && !isStruct) sb.Append(UnityMembers(t));

        // runtime support
        if (!isInterface && !isStruct)
        {
            sb.Append($"    const char* cs_typename() const override {{ return \"{Names.FullName(t)}\"; }}\n");
            sb.Append($"    static const char* cs_static_typename() {{ return \"{Names.FullName(t)}\"; }}\n");
            sb.Append("    bool cs_traced() const override { return true; }\n");
            sb.Append("    void cs_trace(::cs::Tracer& t) override;\n");
        }
        if (o.HasTracedStatics)
            sb.Append("    static void cs_trace_statics(::cs::Tracer& t);\n");
        sb.Append("};\n");
        if (isStruct)
        {
            string cls = N.FlatName(t) + TemplateArgsOf(t);
            sb.Append($"{Template(t)}inline void cs_trace_value(::cs::Tracer& t, const {cls}& v) {{");
            foreach (var f in o.Fields.Where(f => NeedsTrace(f.Type))) sb.Append($" ::cs::TraceField(t, v.{N.Field(f)});");
            sb.Append(" (void)t; (void)v; }\n");
            sb.Append($"{Template(t)}inline const char* cs_box_typename(const {cls}*) {{ return \"{Names.FullName(t)}\"; }}\n");
        }
        return sb.ToString();
    }

    string TemplateArgsOf(INamedTypeSymbol t)
    {
        var tps = Names.AllTypeParameters(t);
        return tps.Count == 0 ? "" : "<" + string.Join(", ", tps.Select(N.TypeParam)) + ">";
    }

    bool BaseHasMethodNamed(INamedTypeSymbol bt, string name)
    {
        for (var b = bt; b != null && N.IsGame(b); b = b.BaseType)
            foreach (var m in b.OriginalDefinition.GetMembers().OfType<IMethodSymbol>())
                if (tr.Methods.ContainsKey(m) && N.Method(m) == name) return true;
        return false;
    }

    // A reference whose C++ type is a pointer to a cs::Object subclass (at the object's start): a
    // class (the game's, the runtime's, a bound engine class, an unmapped placeholder), an array, a
    // string, object, a delegate. Not an interface (a pointer into the object), not a type parameter.
    bool IsObjectRef(ITypeSymbol t)
    {
        if (!Names.IsRef(t) || t.TypeKind is TypeKind.Interface or TypeKind.TypeParameter or TypeKind.Pointer or TypeKind.Dynamic) return false;
        if (t.TypeKind is TypeKind.Array or TypeKind.Delegate) return true;
        if (t.SpecialType is SpecialType.System_String or SpecialType.System_Object) return true;
        return t.TypeKind == TypeKind.Class;
    }

    internal static bool NeedsTrace(ITypeSymbol t) => Names.IsRef(t) || t.TypeKind == TypeKind.TypeParameter || t.IsValueType && t.SpecialType == SpecialType.None && t.TypeKind != TypeKind.Enum;

    string TryType(ITypeSymbol t)
    {
        try { return N.Type(t); }
        catch (TranslateException) { return null; }
    }

    string TypeOrGap(ITypeSymbol t)
    {
        try { return N.Ref(t); }
        catch (TranslateException) { return "::cs::Object* /* unmapped: " + t.ToDisplayString() + " */"; }
    }

    string Params(IMethodSymbol m) => string.Join(", ", m.Parameters.Select(p =>
        TypeOrGap(p.Type) + (p.RefKind is RefKind.Ref or RefKind.Out or RefKind.In ? "&" : "") + " " + Body.ParamName(p)));

    string MethodDecl(IMethodSymbol m, TypeOut o, bool inClass)
    {
        var t = o.T;
        string name = N.Method(m);
        string ret = m.MethodKind is MethodKind.Constructor or MethodKind.StaticConstructor ? "void" : TypeOrGap(m.ReturnType);
        string tmpl = m.IsGenericMethod ? "template <" + string.Join(", ", m.TypeParameters.Select(p => "typename " + N.TypeParam(p))) + "> " : "";
        if (m.IsGenericMethod && (m.IsVirtual || m.IsAbstract || m.IsOverride)) tmpl = "/* virtual generic method: not translatable */ " + tmpl;

        // accessors written in the class itself
        if (m.AssociatedSymbol is IPropertySymbol p && tr.IsAutoProperty(p) && !tr.IsHand(m))
        {
            string f = Names.Ident(p.Name);
            string guard = p.IsStatic && (tr.StaticInitActive(t) || o.Generic && o.HasTracedStatics) ? "__si(); " : "";
            string virt = AccessorVirtual(m);
            if (m.MethodKind == MethodKind.PropertyGet) return $"{(m.IsStatic ? "static " : virt)}{ret} {name}() {{ {guard}return {f}; }}{Override(m)}";
            return $"{(m.IsStatic ? "static " : virt)}void {name}({TypeOrGap(p.Type)} value) {{ {guard}{f} = value; }}{Override(m)}";
        }
        if (m.AssociatedSymbol is IEventSymbol e && tr.IsFieldLikeEvent(e))
        {
            string dt = N.Type(e.Type);
            string f = Names.Ident(e.Name);
            string op = m.MethodKind == MethodKind.EventAdd ? "Combine" : "Remove";
            // (a static event's accessor is a static method: its type's static initialization first,
            // as for a static auto-property; a generic type's registers its static roots)
            string guard = m.IsStatic && (tr.StaticInitActive(t) || o.Generic && o.HasTracedStatics) ? "__si(); " : "";
            return $"{(m.IsStatic ? "static " : AccessorVirtual(m))}void {name}({dt}* value) {{ {guard}{f} = {dt}::{op}({f}, value); }}{Override(m)}";
        }
        if (m.IsGenericMethod && (m.IsVirtual || m.IsAbstract || m.IsOverride || t.TypeKind == TypeKind.Interface || m.ExplicitInterfaceImplementations.Length > 0))
        {
            // C++ has no virtual templates: a plain template here; calls that would dispatch
            // are reported as unsupported (Body.CallCode). Abstract ones throw if reached.
            if (t.TypeKind == TypeKind.Interface || m.IsAbstract)
                return $"{tmpl}{ret} {name}({Params(m)}) {{ ::cs::NotTranslated(\"{Names.FullName(t)}::{m.Name} (a virtual generic method)\"); }}";
            return $"{tmpl}{ret} {name}({Params(m)});";
        }
        string mods = "";
        if (m.IsStatic || m.MethodKind == MethodKind.StaticConstructor) mods = "static ";
        else if (m.IsVirtual || m.IsAbstract || m.IsOverride) mods = "virtual ";
        else if (t.TypeKind == TypeKind.Interface) mods = "virtual ";
        if (m.MethodKind == MethodKind.ExplicitInterfaceImplementation || m.ExplicitInterfaceImplementations.Length > 0) mods = "virtual ";
        string tail = "";
        if (t.TypeKind == TypeKind.Interface || m.IsAbstract) tail = " = 0";
        string ov = Override(m);
        return $"{tmpl}{mods}{ret} {name}({Params(m)}){ov}{tail};";
    }

    string AccessorVirtual(IMethodSymbol m) => m.IsVirtual || m.IsAbstract || m.IsOverride || m.ExplicitInterfaceImplementations.Length > 0 ? "virtual " : "";

    // `override` when the C++ base declares the method: a translated override, an explicit
    // interface implementation, or System.Object's ToString/Equals/GetHashCode.
    // ---- the Unity side of a class ----

    // The messages Unity sends a MonoBehaviour by name (no inheritance needed in C#): each the
    // class declares gets an override of the facade's hook (recomp/src/bind/Scene.h).
    public static readonly string[] Messages =
    {
        "Awake", "OnEnable", "Start", "Update", "FixedUpdate", "LateUpdate", "OnDisable", "OnDestroy",
        "OnTriggerEnter2D", "OnTriggerExit2D", "OnTriggerStay2D", "OnCollisionEnter2D", "OnCollisionExit2D", "OnCollisionStay2D",
        "OnBecameVisible", "OnBecameInvisible", "OnApplicationQuit", "OnApplicationPause", "OnApplicationFocus",
    };

    public static bool DerivesFrom(INamedTypeSymbol t, string fullName)
    {
        for (var b = t; b != null; b = b.BaseType)
            if (b.ToDisplayString() == fullName) return true;
        return false;
    }

    // The fields Instantiate remaps (bind/Engine.cpp): references to UnityEngine.Objects (a
    // GameObject, a component), which Unity makes the copied tree's own where they point into it.
    List<IFieldSymbol> RemapFields(INamedTypeSymbol t) =>
        DerivesFrom(t, "UnityEngine.Object")
            ? t.GetMembers().OfType<IFieldSymbol>()
                .Where(f => !f.IsStatic && !f.IsConst && tr.IsFieldUsedOrFull(f) && f.Type is INamedTypeSymbol ft && ft.TypeKind == TypeKind.Class &&
                            DerivesFrom(ft, "UnityEngine.Object"))
                .ToList()
            : new List<IFieldSymbol>();

    static bool IsSerializable(INamedTypeSymbol t) =>
        t.GetAttributes().Any(a => a.AttributeClass?.ToDisplayString() == "System.SerializableAttribute");

    string UnityMembers(INamedTypeSymbol t)
    {
        var sb = new StringBuilder();
        if (!DerivesFrom(t, "UnityEngine.Object"))
        {
            // A [Serializable] class's fields as a JSON file or an asset gives them (FullSerializer's,
            // JsonUtility's reflection): not virtual, the base's after its own.
            if (!IsSerializable(t) || t.TypeKind != TypeKind.Class) return "";
            var sf = t.GetMembers().OfType<IFieldSymbol>().Where(f => !f.IsStatic && !f.IsConst && tr.IsFieldUsedOrFull(f) && SerialKind(f.Type) != null).ToList();
            bool baseHas = t.BaseType != null && N.IsGame(t.BaseType) && IsSerializable(t.BaseType);
            // (emitted even without fields: SerialObject reads any [Serializable] class through it)
            var sd = Defined(sb, t, "bool", "cs_SetField(const char* name, const ::UnityEngine::SerialValue& v)", "");
            NameSwitch(sd, "name", sf.Select(f => f.Name), false, sf.Select(f => $"this->{N.Field(f)} = {SerialKind(f.Type)}; return true;").ToList());
            sd.Append(baseHas ? $"    return {N.Type(t.BaseType)}::cs_SetField(name, v);\n}}\n" : "    (void)v;\n    return false;\n}\n");
            return sb.ToString();
        }
        // (A class whose engine base has no binding yet (StateMachineBehaviour, Selectable...) is no
        // UnityEngine::Object in C++: none of Unity's hooks to override.)
        if (!EngineBaseMapped(t)) return "";
        bool mono = DerivesFrom(t, "UnityEngine.MonoBehaviour");
        // Instantiate's copy (bind/Engine.cpp): the whole object.
        if (!t.IsAbstract && !t.IsGenericType && Names.AllTypeParameters(t).Count == 0)
            Defined(sb, t, "::UnityEngine::Object*", "cs_Clone()", " override").Append($"    return ::cs::gcnew<{N.FlatName(t)}>(*this);\n}}\n");
        // Instantiate's remap (bind/Engine.cpp; defined with cs_trace).
        if (RemapFields(t).Count > 0) sb.Append("    void cs_Remap(const ::UnityEngine::Remap& r) override;\n");
        // (A stubbed class's messages aren't hooked: what they do is the driver's to stand in for.)
        var mine = t.GetMembers().OfType<IMethodSymbol>().Where(m => tr.Methods.TryGetValue(m, out var mr) && !mr.Stub && !m.IsStatic && m.MethodKind == MethodKind.Ordinary && !m.IsGenericMethod).ToList();
        if (mono)
        {
            foreach (var name in Messages)
            {
                var m = mine.FirstOrDefault(x => x.Name == name);
                if (m == null) continue;
                string args = string.Join(", ", m.Parameters.Select(Body.ParamName));
                string ps = string.Join(", ", m.Parameters.Select(p => TypeOrGap(p.Type) + " " + Body.ParamName(p)));
                // (a message with a parameter Unity calls only with its type: Collider2D, Collision2D, bool)
                sb.Append($"    void cs_{name}({ps}) override {{ this->{N.Method(m)}({args}); }}\n");
            }
            // SendMessage / Invoke / an Animator's events: by name, the class's own methods first.
            var named = mine.Where(m => m.Parameters.Length <= 1 && m.Parameters.All(p => p.RefKind == RefKind.None)).ToList();
            if (named.Count > 0)
            {
                string bt = N.Type(t.BaseType);
                var ob = Defined(sb, t, "bool", "cs_Message(::cs::String* name, const ::UnityEngine::MessageArgs& a)", " override");
                var groups = named.GroupBy(m => m.Name).ToList();
                var cases = new List<string>();
                foreach (var g in groups)
                {
                    // the overload without parameters first, else the first whose argument converts;
                    // none: the base class's (as when no name matched)
                    string code = "break;";
                    foreach (var m in g.OrderBy(m => m.Parameters.Length))
                    {
                        if (m.Parameters.Length == 0) { code = $"this->{N.Method(m)}(); return true;"; break; }
                        string arg = MessageArg(m.Parameters[0].Type);
                        if (arg == null) continue;
                        code = $"this->{N.Method(m)}({arg}); return true;";
                        break;
                    }
                    cases.Add(code);
                }
                NameSwitch(ob, "name", groups.Select(g => g.Key), true, cases);
                ob.Append($"    return {bt}::cs_Message(name, a);\n}}\n");
            }
            // StartCoroutine(string): an IEnumerator method without parameters, by name.
            var routines = mine.Where(m => m.Parameters.Length == 0 && m.ReturnType.ToDisplayString() == "System.Collections.IEnumerator").ToList();
            if (routines.Count > 0)
            {
                string bt = N.Type(t.BaseType);
                var cd = Defined(sb, t, "::cs::IEnumerator*", "cs_Coroutine(::cs::String* name)", " override");
                // (the first of a name, as the comparisons in order did)
                var byName = routines.GroupBy(m => m.Name).Select(g => g.First()).ToList();
                NameSwitch(cd, "name", byName.Select(m => m.Name), true, byName.Select(m => $"return this->{N.Method(m)}();").ToList());
                cd.Append($"    return {bt}::cs_Coroutine(name);\n}}\n");
            }
        }
        // The serialized fields a prefab or asset sets (the simple kinds; others the caller does).
        var fields = t.GetMembers().OfType<IFieldSymbol>().Where(f => !f.IsStatic && !f.IsConst && tr.IsFieldUsedOrFull(f) && SerialKind(f.Type) != null).ToList();
        if (fields.Count > 0)
        {
            string bt = N.Type(t.BaseType);
            var fd = Defined(sb, t, "bool", "cs_SetField(const char* name, const ::UnityEngine::SerialValue& v)", " override");
            NameSwitch(fd, "name", fields.Select(f => f.Name), false, fields.Select(f => $"this->{N.Field(f)} = {SerialKind(f.Type)}; return true;").ToList());
            fd.Append($"    return {bt}::cs_SetField(name, v);\n}}\n");
        }
        var empties = t.GetMembers().OfType<IFieldSymbol>().Where(f => IsSerializedField(f) && tr.IsFieldUsedOrFull(f) && SerialEmpty(f.Type) != null).ToList();
        if (empties.Count > 0)
        {
            string bt = N.Type(t.BaseType);
            var ed = Defined(sb, t, "void", "cs_SerialInit()", " override");
            ed.Append($"    {bt}::cs_SerialInit();\n");
            foreach (var f in empties) ed.Append($"    if (!this->{N.Field(f)}) this->{N.Field(f)} = {SerialEmpty(f.Type)};\n");
            ed.Append("}\n");
        }
        return sb.ToString();
    }

    // A dispatch by name: a table of the names (constant data) searched by the runtime's one loop
    // (cs::NameIndex), then a switch to the case's code. Names are unique; the first equal one wins,
    // as the chain of comparisons it replaces. utf16: the name is a cs::String* (messages), else a
    // const char* (serialized fields).
    static void NameSwitch(StringBuilder ob, string key, IEnumerable<string> names, bool utf16, List<string> cases)
    {
        var list = names.ToList();
        if (list.Count == 0) return;
        // (identifiers in ASCII: one byte a character in the table, compared with the UTF-16 name)
        bool wide = utf16 && list.Any(n => n.Any(c => c >= 128 || c == '"' || c == '\\'));
        string lit(string n) => wide ? Names.U16Literal(n) : "\"" + n + "\"";
        ob.Append($"    static const {(wide ? "char16_t" : "char")}* const names_[] = {{ {string.Join(", ", list.Select(lit))} }};\n");
        ob.Append($"    switch (::cs::NameIndex({key}, names_, {list.Count})) {{\n");
        for (int i = 0; i < list.Count; i++) ob.Append($"    case {i}: {cases[i]}\n");
        ob.Append("    default: break;\n    }\n");
    }

    // A class Instantiate copies (a UnityEngine.Object's, with a C++ engine base): its copy
    // constructor out of line.
    bool OutOfLineCopy(INamedTypeSymbol t) =>
        t.TypeKind == TypeKind.Class && DerivesFrom(t, "UnityEngine.Object") && EngineBaseMapped(t);

    // Members of a class defined with its methods (in its .cpp, or with the templates), not in the
    // class: a body there would be compiled by every file that includes game.h (and instantiate the
    // templates it names, List<T> and the rest, in each), and may call a method returning a struct
    // not complete yet.
    readonly Dictionary<INamedTypeSymbol, StringBuilder> outOfLine = new(SymbolEqualityComparer.Default);
    StringBuilder OutOfLine(INamedTypeSymbol t)
    {
        if (!outOfLine.TryGetValue(t, out var sb)) outOfLine[t] = sb = new StringBuilder();
        return sb;
    }

    // Declares `ret sig` in the class (decl) and opens its definition out of line; the caller
    // appends the body and the closing brace.
    StringBuilder Defined(StringBuilder decl, INamedTypeSymbol t, string ret, string sig, string tail)
    {
        decl.Append($"    {ret} {sig}{tail};\n");
        var ob = OutOfLine(t);
        ob.Append($"{Template(t)}{ret} {N.QualifiedGameName(t)[2..]}{TemplateArgsOf(t)}::{sig} {{\n");
        return ob;
    }

    // A constructor without parameters (AddComponent's cs::New<T>() runs it). (A
    // MonoBehaviour with only constructors that take arguments: Unity makes it without running one;
    // not done yet, so not in cs_AddComponent.)
    bool HasDefaultCtor(INamedTypeSymbol t) =>
        t.InstanceConstructors.Any(c => c.Parameters.Length == 0);

    // Every engine class between t and UnityEngine.Object has a C++ type (a binding), so t's C++
    // bases reach UnityEngine::Object.
    bool EngineBaseMapped(INamedTypeSymbol t)
    {
        for (var b = t.BaseType; b != null && b.SpecialType != SpecialType.System_Object; b = b.BaseType)
        {
            if (N.IsGame(b)) continue;
            string bt = TryType(b);
            if (bt == null || bt.Contains("::cs::Unmapped")) return false;
            if (b.ToDisplayString() == "UnityEngine.Object") return true;
        }
        return true;
    }

    // An Animator event's or SendMessage's argument as the method's parameter type.
    string MessageArg(ITypeSymbol t) => t.SpecialType switch
    {
        SpecialType.System_Single => "a.event ? a.event->floatParameter : ::cs::Unbox<float>(a.value)",
        SpecialType.System_Int32 => "a.event ? a.event->intParameter : ::cs::Unbox<int32_t>(a.value)",
        SpecialType.System_String => "a.event ? ::cs::String::FromUtf8(a.event->stringParameter) : ::cs::Cast<::cs::String>(a.value)",
        SpecialType.System_Boolean => "::cs::Unbox<bool>(a.value)",
        SpecialType.System_Object => "a.value",
        _ => Names.IsRef(t) && t.TypeKind == TypeKind.Class ? $"::cs::Cast<{N.Type(t)}>(a.value)" : null,
    };

    // How a serialized field reads from a prefab's value, or null for a kind the caller sets.
    string SerialKind(ITypeSymbol t)
    {
        switch (t.SpecialType)
        {
            case SpecialType.System_Boolean: return "v.AsBool()";
            case SpecialType.System_Int32: return "v.AsInt()";
            case SpecialType.System_Single: return "v.AsFloat()";
            case SpecialType.System_Double: return "static_cast<double>(v.AsFloat())";
            case SpecialType.System_String: return "v.AsString()";
        }
        if (t.TypeKind == TypeKind.Enum) return TryType(t) is string et && !et.Contains("::cs::Unmapped") ? $"static_cast<{et}>(v.AsInt())" : null;
        string n = t.ToDisplayString();
        if (n == "UnityEngine.Vector2") return "v.AsVector2()";
        if (n == "UnityEngine.Vector3") return "v.AsVector3()";
        if (n == "UnityEngine.Color") return "v.AsColor()";
        // A reference to an object of the prefab (its path below the prefab's root): the object, or
        // its component of the field's type.
        if (n == "UnityEngine.GameObject") return "v.AsGameObject()";
        if (n == "UnityEngine.Sprite") return "v.AsSprite()";
        if (t is INamedTypeSymbol nt && t.TypeKind == TypeKind.Class && DerivesFrom(nt, "UnityEngine.Component") && (N.IsGame(nt) || tr.Bind.FindType(nt) != null))
            return $"(v.AsGameObject() ? v.AsGameObject()->template GetComponent<{N.Ref(t)}>() : nullptr)";
        // Lists and arrays of what reads element by element, a [Serializable] game class's object.
        if (t is INamedTypeSymbol lt && lt.IsGenericType && lt.OriginalDefinition.ToDisplayString() == "System.Collections.Generic.List<T>" && SerialElement(lt.TypeArguments[0]))
            return $"::UnityEngine::SerialList<{N.Ref(lt.TypeArguments[0])}>(v)";
        if (t is IArrayTypeSymbol at && at.Rank == 1 && SerialElement(at.ElementType))
            return $"::UnityEngine::SerialArray<{N.Ref(at.ElementType)}>(v)";
        if (t is INamedTypeSymbol ct && SerialClass(ct))
            return $"::UnityEngine::SerialObject<{N.Type(ct)}>(v)";
        return null;
    }

    // A [Serializable] game class SerialObject makes (bind/Serial.h): its constructor, its cs_SetField.
    bool SerialClass(INamedTypeSymbol ct) =>
        ct.TypeKind == TypeKind.Class && N.IsGame(ct) && IsSerializable(ct) && !DerivesFrom(ct, "UnityEngine.Object") && !ct.IsAbstract &&
        Names.AllTypeParameters(ct).Count == 0 && ct.InstanceConstructors.FirstOrDefault(c => c.Parameters.Length == 0) is IMethodSymbol ctor &&
        tr.Methods.TryGetValue(ctor, out var r) && !r.Stub;

    // An element SerialRead (bind/Serial.h) reads.
    bool SerialElement(ITypeSymbol t)
    {
        if (t.SpecialType is SpecialType.System_Boolean or SpecialType.System_Int32 or SpecialType.System_Single or SpecialType.System_Double or SpecialType.System_String) return true;
        if (t.TypeKind == TypeKind.Enum) return TryType(t) is string et && !et.Contains("::cs::Unmapped");
        string n = t.ToDisplayString();
        if (n is "UnityEngine.Vector2" or "UnityEngine.Vector3" or "UnityEngine.Color" or "UnityEngine.GameObject") return true;
        if (t is INamedTypeSymbol nt && t.TypeKind == TypeKind.Class && DerivesFrom(nt, "UnityEngine.Object") && (N.IsGame(nt) || tr.Bind.FindType(nt) != null)) return true;
        return t is INamedTypeSymbol ct && SerialClass(ct);
    }

    // Unity serializes it: public (or [SerializeField]), not static, const, readonly or [NonSerialized].
    static bool IsSerializedField(IFieldSymbol f)
    {
        if (f.IsStatic || f.IsConst || f.IsReadOnly || f.AssociatedSymbol != null) return false;
        var attrs = f.GetAttributes().Select(a => a.AttributeClass?.ToDisplayString()).ToList();
        if (attrs.Contains("System.NonSerializedAttribute")) return false;
        return f.DeclaredAccessibility == Accessibility.Public || attrs.Contains("UnityEngine.SerializeField");
    }

    // What a serialized field of a loaded object is when the data doesn't say (cs_SerialInit): an
    // empty string, list or array, a [Serializable] class's new object; null: a kind it leaves be.
    string SerialEmpty(ITypeSymbol t)
    {
        if (t.SpecialType == SpecialType.System_String) return "::cs::String::get_Empty()";
        if (t is INamedTypeSymbol lt && lt.IsGenericType && lt.OriginalDefinition.ToDisplayString() == "System.Collections.Generic.List<T>" && SerialElement(lt.TypeArguments[0]))
            return $"::cs::New<{N.Type(lt)}>()";
        if (t is IArrayTypeSymbol at && at.Rank == 1 && SerialElement(at.ElementType))
            return $"::cs::Array<{N.Ref(at.ElementType)}>::New(0)";
        if (t is INamedTypeSymbol ct && SerialClass(ct))
            return $"::cs::New<{N.Type(ct)}>()";
        return null;
    }

    // Is the interface a C++ base: a game interface, or one bindings.tsv maps.
    bool InterfaceMapped(INamedTypeSymbol i) => N.IsGame(i) || tr.Bind.FindType(i) != null;

    string Override(IMethodSymbol m)
    {
        if (m.ExplicitInterfaceImplementations.Length > 0)
        {
            var im = m.ExplicitInterfaceImplementations[0];
            return InterfaceMapped(im.ContainingType) && !im.IsGenericMethod ? " override" : "";
        }
        if (!m.IsOverride) return "";
        var o = m.OverriddenMethod;
        if (o == null) return "";
        if (N.IsGame(o) && tr.Methods.ContainsKey(o.OriginalDefinition)) return " override";
        var root = o;
        while (root.OverriddenMethod != null) root = root.OverriddenMethod;
        if (root.ContainingType.SpecialType == SpecialType.System_Object && root.Name is "ToString" or "Equals" or "GetHashCode" && !m.ContainingType.IsValueType) return " override";
        return "";
    }

    // Interface members the class maps to an ordinary method: forwarders under the interface's name.
    string Forwarders(INamedTypeSymbol t)
    {
        var sb = new StringBuilder();
        var direct = new HashSet<INamedTypeSymbol>(SymbolEqualityComparer.Default);
        foreach (var i in t.Interfaces)
        {
            direct.Add(i);
            foreach (var ii in i.AllInterfaces) direct.Add(ii);
        }
        var done = new HashSet<string>(StringComparer.Ordinal);
        foreach (var i in direct)
        {
            if (!InterfaceMapped(i)) continue;
            foreach (var im in i.GetMembers().OfType<IMethodSymbol>())
            {
                if (N.IsGame(im) && !tr.Methods.ContainsKey(im.OriginalDefinition)) continue;
                if (im.IsGenericMethod) continue; // C++ has no virtual templates: not dispatched through the interface
                var impl = t.FindImplementationForInterfaceMember(im) as IMethodSymbol;
                if (impl == null) { sb.Append($"    // no implementation of {im}\n"); continue; }
                if (impl.ExplicitInterfaceImplementations.Any(x => SymbolEqualityComparer.Default.Equals(x.OriginalDefinition, im.OriginalDefinition))
                    && SymbolEqualityComparer.Default.Equals(impl.ContainingType.OriginalDefinition, t.OriginalDefinition)) continue;
                string iname = N.InterfaceMember(im);
                string ret = TypeOrGap(im.ReturnType);
                string ps = string.Join(", ", im.Parameters.Select(p => TypeOrGap(p.Type) + (p.RefKind != RefKind.None ? "&" : "") + " " + Body.ParamName(p)));
                string sig = iname + "(" + ps + ")";
                if (!done.Add(sig)) continue;
                string args = string.Join(", ", im.Parameters.Select(Body.ParamName));
                string target;
                if (!N.IsGame(impl))
                {
                    // implemented by an engine base class: call through it by convention
                    target = $"this->{Names.Ident(impl.Name)}({args})";
                }
                else
                {
                    tr.NeedMethod(impl);
                    target = $"this->{N.Method(impl)}({args})";
                }
                sb.Append($"    {ret} {sig} override {{ {(ret == "void" ? "" : "return ")}{target}; }}\n");
            }
        }
        return sb.ToString();
    }

    // ---- definitions --------------------------------------------------------------------------------------

    void Definitions(TypeOut o, StringBuilder typeSb, StringBuilder templates)
    {
        var t = o.T;
        string tmpl = Template(t);
        // no leading :: : `int32_t ::gen::X::f` would parse as `int32_t::gen...`
        string cls = N.QualifiedGameName(t)[2..] + TemplateArgsOf(t);
        if (t.TypeKind == TypeKind.Interface) return;
        var sb = typeSb;

        // static fields
        foreach (var f in o.StaticFields)
            sb.Append($"{tmpl}{TypeOrGap(f.Type)} {cls}::{N.Field(f)}{{}};\n");
        bool si = tr.StaticInitActive(t);
        bool siGeneric = o.Generic && o.HasTracedStatics;
        if (si || siGeneric) sb.Append($"{tmpl}int8_t {cls}::cs_cctor_state_ = 0;\n");
        if (o.HasTracedStatics)
        {
            sb.Append($"{tmpl}void {cls}::cs_trace_statics(::cs::Tracer& t) {{");
            foreach (var f in o.StaticFields.Where(f => NeedsTrace(f.Type))) sb.Append($" ::cs::TraceField(t, {N.Field(f)});");
            foreach (var e in o.Events.Where(e => e.IsStatic)) sb.Append($" ::cs::TraceField(t, {Names.Ident(e.Name)});");
            sb.Append(" }\n");
            if (!o.Generic) sb.Append($"static const bool cs_roots_{N.FlatName(t)} = ::cs::RegisterRoots(&{cls}::cs_trace_statics);\n");
        }
        if (si && !o.Methods.Any(m => m.MethodKind == MethodKind.StaticConstructor))
        {
            // a static constructor made of the static field initializers alone
            sb.Append($"{tmpl}void {cls}::__cctor() {{\n");
            sb.Append(ImplicitCctor(t));
            sb.Append("}\n");
        }

        // cs_trace
        if (t.TypeKind == TypeKind.Class)
        {
            sb.Append($"{tmpl}void {cls}::cs_trace(::cs::Tracer& t) {{\n");
            var bt = t.BaseType;
            if (bt != null && bt.SpecialType != SpecialType.System_Object) sb.Append($"    {N.Type(bt)}::cs_trace(t);\n");
            // References to objects (classes, arrays, strings, delegates: cs::Object at the start of
            // each) by their offsets, marked by the runtime's one loop; the rest (interfaces, structs,
            // type parameters) one by one. (The order objects are marked in isn't observable.)
            var refs = o.Fields.Where(f => IsObjectRef(f.Type)).Select(f => N.Field(f))
                .Concat(o.Events.Where(e => !e.IsStatic && IsObjectRef(e.Type)).Select(e => Names.Ident(e.Name))).ToList();
            if (refs.Count > 0)
            {
                sb.Append($"    static const uint16_t refs_[] = {{ {string.Join(", ", refs.Select(f => $"offsetof({cls}, {f})"))} }};\n");
                sb.Append($"    t.MarkRefs(this, refs_, {refs.Count});\n");
            }
            foreach (var f in o.Fields.Where(f => NeedsTrace(f.Type) && !IsObjectRef(f.Type))) sb.Append($"    ::cs::TraceField(t, this->{N.Field(f)});\n");
            foreach (var e in o.Events.Where(e => !e.IsStatic && !IsObjectRef(e.Type))) sb.Append($"    ::cs::TraceField(t, this->{Names.Ident(e.Name)});\n");
            sb.Append("    (void)t;\n}\n");
        }
        // cs_Remap (Instantiate's: RemapFields)
        if (t.TypeKind == TypeKind.Class && EngineBaseMapped(t) && RemapFields(t) is var remap && remap.Count > 0)
        {
            sb.Append($"{tmpl}void {cls}::cs_Remap(const ::UnityEngine::Remap& r) {{\n");
            sb.Append($"    {N.Type(t.BaseType)}::cs_Remap(r);\n");
            foreach (var f in remap) sb.Append($"    r.Field(this->{N.Field(f)});\n");
            sb.Append("}\n");
        }
        foreach (var e in o.Events.Where(e => e.IsStatic))
            sb.Append($"{tmpl}{N.Ref(e.Type)} {cls}::{Names.Ident(e.Name)}{{}};\n");
        if (outOfLine.TryGetValue(t, out var ool)) sb.Append(ool);

        foreach (var m in o.Methods)
        {
            var r = tr.Methods[m];
            if (r.Hand) continue; // (defined by hand: units.txt's `hand`)
            if (m.AssociatedSymbol is IPropertySymbol p && tr.IsAutoProperty(p)) continue;
            if (m.AssociatedSymbol is IEventSymbol e && tr.IsFieldLikeEvent(e)) continue;
            if (m.IsAbstract || t.TypeKind == TypeKind.Interface) continue;
            string name = N.Method(m) + (r.Wrap ? "__game" : "");
            string ret = m.MethodKind is MethodKind.Constructor or MethodKind.StaticConstructor ? "void" : TypeOrGap(m.ReturnType);
            string mt = m.IsGenericMethod ? "template <" + string.Join(", ", m.TypeParameters.Select(tp => "typename " + N.TypeParam(tp))) + "> " : "";
            // a generic method's definition is a template: in the header, for every user
            var msb = m.IsGenericMethod && !o.Generic ? templates : sb;
            msb.Append($"{tmpl}{mt}{ret} {cls}::{name}({Params(m)}) {{\n");
            if (r.Translated && r.Body != null)
            {
                msb.Append(r.Body);
                r.Lines = r.Body.Count(c => c == '\n');
            }
            else
            {
                string why = r.Stub ? "stubbed by units.txt (reaching it is an error)" : r.Error ?? ("missing: " + string.Join("; ", r.Gaps));
                msb.Append($"    // not translated: {why.Replace("\n", " ")}\n");
                msb.Append($"    ::cs::NotTranslated(\"{Names.FullName(t)}::{m.Name}\");\n");
                foreach (var prm in m.Parameters) msb.Append($"    (void){Body.ParamName(prm)};\n");
                if (ret != "void") msb.Append($"    return {DefaultOf(m.ReturnType)};\n");
            }
            msb.Append("}\n");
        }
        sb.Append('\n');
    }

    string DefaultOf(ITypeSymbol t) => Names.IsRef(t) ? "nullptr" : $"{TypeOrGap(t)}{{}}";

    string ImplicitCctor(INamedTypeSymbol t)
    {
        // Translated through a synthesized static constructor symbol when Roslyn has one, else here.
        var cctor = t.StaticConstructors.FirstOrDefault();
        if (cctor != null && tr.Methods.TryGetValue(cctor, out var r) && r.Body != null) return r.Body;
        try
        {
            var mt = new MethodTranslator(tr, cctor ?? throw new TranslateException("no static constructor symbol"));
            return mt.Translate() ?? "";
        }
        catch (TranslateException e)
        {
            return $"    // not translated: {e.Message}\n    ::cs::NotTranslated(\"{Names.FullName(t)}::.cctor\");\n";
        }
    }

    // ---- the report -------------------------------------------------------------------------------------------

    void WriteReport()
    {
        var sb = new StringBuilder("# tools/translate: every translated method. status: ok, error (an unsupported construct), gaps (bindings missing)\n# type\tmethod\tstatus\tdetail\n");
        foreach (var (m, r) in tr.Methods.OrderBy(kv => Names.FullName(kv.Key.ContainingType), StringComparer.Ordinal).ThenBy(kv => kv.Key.Name, StringComparer.Ordinal))
        {
            string status = r.Hand ? "hand" : r.Stub ? "stub" : r.Error != null ? "error" : r.Gaps.Count > 0 ? "gaps" : r.Wrap ? "ok (wrapped)" : "ok";
            string detail = r.Error ?? string.Join("; ", r.Gaps);
            sb.Append($"{Names.FullName(m.ContainingType)}\t{m.ToDisplayString(SymbolDisplayFormat.MinimallyQualifiedFormat)}\t{status}\t{detail.Replace('\t', ' ').Replace('\n', ' ')}\n");
        }
        File.WriteAllText(Path.Combine(outDir, "report.tsv"), sb.ToString(), new UTF8Encoding(false));
    }
