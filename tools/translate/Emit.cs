using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace MoonlighterTranslate;

// Writes the translation (docs/translator_plan.md, "Output"):
//   game.h        every translated type: forward declarations, enums, then the classes,
//                 structs and interfaces in dependency order (bases and value fields first), then
//                 the bodies of generic types and methods (templates);
//   <file>.cpp    the bodies of the methods declared in that C# file, its static fields;
//   sources.cmake the .cpp files, for recomp/CMakeLists.txt;
//   report.tsv    every method: translated, or why not (an unsupported construct, missing bindings).
public sealed class Emitter
{
    readonly Translator tr;
    readonly Names N;
    readonly string outDir;

    public Emitter(Translator tr, string outDir)
    {
        this.tr = tr;
        N = tr.N;
        this.outDir = outDir;
    }

    sealed class TypeOut
    {
        public INamedTypeSymbol T;
        public string File; // the C# file it comes from
        public List<IMethodSymbol> Methods = new();
        public List<IFieldSymbol> Fields = new();
        public List<IFieldSymbol> StaticFields = new();
        public List<IEventSymbol> Events = new();
        public bool Generic;
    }

    public void Write()
    {
        Directory.CreateDirectory(outDir);
        var outs = new Dictionary<INamedTypeSymbol, TypeOut>(SymbolEqualityComparer.Default);
        foreach (var t in tr.Types) outs[t] = Collect(t);

        // ---- game.h ----
        var h = new StringBuilder();
        h.Append("// Generated by tools/translate from the game's Assembly-CSharp.dll: do not edit, do not commit.\n");
        h.Append("#pragma once\n\n#include \"cs/Runtime.h\"\n");
        foreach (var inc in tr.Includes.OrderBy(x => x, StringComparer.Ordinal)) h.Append($"#include \"{inc}\"\n");
        h.Append('\n');

        // forward declarations and enums
        var ordered = Order(outs.Values.ToList());
        foreach (var o in ordered.Where(o => o.T.TypeKind == TypeKind.Enum)) h.Append(Namespaced(o.T, EnumDecl(o.T)));
        foreach (var o in ordered.Where(o => o.T.TypeKind is TypeKind.Class or TypeKind.Struct or TypeKind.Interface))
            h.Append(Namespaced(o.T, Template(o.T) + (o.T.TypeKind == TypeKind.Interface || o.T.TypeKind == TypeKind.Struct ? "struct " : "class ") + N.FlatName(o.T) + ";\n"));
        h.Append('\n');

        var cpp = new Dictionary<string, StringBuilder>(StringComparer.Ordinal);
        StringBuilder Cpp(string file)
        {
            if (!cpp.TryGetValue(file, out var sb))
            {
                cpp[file] = sb = new StringBuilder();
                sb.Append("// Generated by tools/translate from the game's ").Append(file).Append(": do not edit, do not commit.\n");
                sb.Append("#include \"game.h\"\n\n");
            }
            return sb;
        }
        var templates = new StringBuilder();

        foreach (var o in ordered)
        {
            if (o.T.TypeKind == TypeKind.Enum) continue;
            h.Append(Namespaced(o.T, ClassDecl(o)));
            var defs = o.Generic ? templates : Cpp(o.File);
            Definitions(o, defs, templates);
        }
        h.Append("\n// ---- generic types and methods ----\n\n").Append(templates);

        File.WriteAllText(Path.Combine(outDir, "game.h"), h.ToString(), new UTF8Encoding(false));
        var written = new List<string>();
        foreach (var (file, sb) in cpp.OrderBy(kv => kv.Key, StringComparer.Ordinal))
        {
            string name = file.Replace('/', '_').Replace('\\', '_').Replace(".cs", ".cpp");
            File.WriteAllText(Path.Combine(outDir, name), sb.ToString(), new UTF8Encoding(false));
            written.Add(name);
        }
        // Old files of a previous translation would still be listed by a glob: only the list counts.
        var cm = new StringBuilder("# Generated by tools/translate: the translated game sources.\nset(ML_GEN_SOURCES\n");
        foreach (var w in written) cm.Append("    ${ML_GEN_DIR}/").Append(w).Append('\n');
        cm.Append(")\n");
        File.WriteAllText(Path.Combine(outDir, "sources.cmake"), cm.ToString(), new UTF8Encoding(false));
        WriteReport();
    }

    // ---- collecting a type's members -------------------------------------------------------------------

    TypeOut Collect(INamedTypeSymbol t)
    {
        var o = new TypeOut { T = t, File = FileOf(t), Generic = Names.AllTypeParameters(t).Count > 0 };
        foreach (var m in t.GetMembers())
        {
            switch (m)
            {
                case IMethodSymbol ms when tr.Methods.ContainsKey(ms):
                    o.Methods.Add(ms);
                    break;
                case IFieldSymbol f when !f.IsConst:
                    bool used = tr.IsFieldUsed(f) || tr.IsFull(t) && f.AssociatedSymbol == null;
                    // an auto-property's backing field comes with its accessors
                    if (f.AssociatedSymbol is IPropertySymbol p && (p.GetMethod != null && tr.Methods.ContainsKey(p.GetMethod) || p.SetMethod != null && tr.Methods.ContainsKey(p.SetMethod))) used = true;
                    if (f.AssociatedSymbol is IEventSymbol) used = false; // events emit their own field
                    if (!used) break;
                    if (f.IsStatic) o.StaticFields.Add(f);
                    else o.Fields.Add(f);
                    break;
                case IEventSymbol e when tr.IsEventUsed(e) || tr.IsFull(t):
                    if (tr.IsFieldLikeEvent(e)) o.Events.Add(e);
                    break;
            }
        }
        // the implicit static constructor of static field initializers
        return o;
    }

    string FileOf(INamedTypeSymbol t)
    {
        var r = t.DeclaringSyntaxReferences.FirstOrDefault();
        if (r == null) return "unknown.cs";
        return Path.GetRelativePath(tr.GC.DecompDir, r.SyntaxTree.FilePath).Replace('\\', '/');
    }

    // Bases, interfaces and value fields before the types that need them complete.
    List<TypeOut> Order(List<TypeOut> all)
    {
        var byType = all.ToDictionary(o => o.T, o => o, SymbolEqualityComparer.Default);
        var result = new List<TypeOut>();
        var state = new Dictionary<INamedTypeSymbol, int>(SymbolEqualityComparer.Default);
        void Visit(TypeOut o)
        {
            if (state.TryGetValue(o.T, out int s))
            {
                if (s == 1) throw new TranslateException($"cyclic value types at {o.T}");
                return;
            }
            state[o.T] = 1;
            foreach (var d in Deps(o))
                if (byType.TryGetValue(d.OriginalDefinition, out var od)) Visit(od);
            state[o.T] = 2;
            result.Add(o);
        }
        foreach (var o in all.OrderBy(o => N.QualifiedGameName(o.T), StringComparer.Ordinal)) Visit(o);
        return result;
    }

    IEnumerable<INamedTypeSymbol> Deps(TypeOut o)
    {
        var t = o.T;
        if (t.BaseType != null) yield return t.BaseType;
        foreach (var i in t.Interfaces) yield return i;
        foreach (var f in o.Fields)
            foreach (var d in ValueDeps(f.Type)) yield return d;
        foreach (var m in o.Methods)
        {
            // inline accessors use their field's type
        }
    }

    IEnumerable<INamedTypeSymbol> ValueDeps(ITypeSymbol t)
    {
        if (t is INamedTypeSymbol nt && t.IsValueType)
        {
            yield return nt;
            foreach (var a in nt.TypeArguments)
                foreach (var d in ValueDeps(a)) yield return d;
        }
    }

    // ---- declarations -----------------------------------------------------------------------------------

    string Namespaced(INamedTypeSymbol t, string body)
    {
        string ns = Names.NamespacePath(t);
        string open = "namespace gen {" + (ns.Length > 0 ? string.Concat(ns.Split("::").Select(p => $" namespace {p} {{")) : "") + "\n";
        string close = "}" + (ns.Length > 0 ? new string('}', ns.Split("::").Length) : "") + "\n\n";
        return open + body + close;
    }

    string Template(INamedTypeSymbol t)
    {
        var tps = Names.AllTypeParameters(t);
        return tps.Count == 0 ? "" : "template <" + string.Join(", ", tps.Select(p => "typename " + N.TypeParam(p))) + "> ";
    }

    string EnumDecl(INamedTypeSymbol t)
    {
        var sb = new StringBuilder();
        string u = N.Type(t.EnumUnderlyingType);
        sb.Append($"enum class {N.FlatName(t)} : {u} {{\n");
        foreach (var f in t.GetMembers().OfType<IFieldSymbol>().Where(f => f.HasConstantValue))
            sb.Append($"    {Names.Ident(f.Name)} = {Names.Literal(Convert.ChangeType(f.ConstantValue, f.ConstantValue.GetType()), t.EnumUnderlyingType)},\n");
        sb.Append("};\n");
        // boxing support: the name and ToString (Enum.ToString: the member's name, else the number)
        string full = Names.FullName(t);
        string cls = N.FlatName(t);
        sb.Append($"inline const char* cs_box_typename(const {cls}*) {{ return \"{full}\"; }}\n");
        sb.Append($"inline ::cs::String* cs_box_tostring({cls} v) {{\n    switch (static_cast<{u}>(v)) {{\n");
        var seen = new HashSet<object>();
        foreach (var f in t.GetMembers().OfType<IFieldSymbol>().Where(f => f.HasConstantValue))
            if (seen.Add(f.ConstantValue))
                sb.Append($"    case {Names.Literal(f.ConstantValue, t.EnumUnderlyingType)}: return {Names.StringLiteral(f.Name)};\n");
        sb.Append($"    default: return ::cs::ToString(static_cast<{(u is "int8_t" or "uint8_t" or "int16_t" or "uint16_t" ? "int32_t" : u)}>(v));\n    }}\n}}\n");
        return sb.ToString();
    }

    string ClassDecl(TypeOut o)
    {
        var t = o.T;
        var sb = new StringBuilder();
        sb.Append(Template(t));
        bool isInterface = t.TypeKind == TypeKind.Interface;
        bool isStruct = t.TypeKind == TypeKind.Struct;
        sb.Append(isInterface || isStruct ? "struct " : "class ").Append(N.FlatName(t));
        var bases = new List<string>();
        if (!isInterface && !isStruct)
        {
            var bt = t.BaseType;
            if (bt == null || bt.SpecialType == SpecialType.System_Object) bases.Add("public ::cs::Object");
            else bases.Add("public " + N.Type(bt));
        }
        foreach (var i in t.Interfaces)
        {
            string it = TryType(i);
            if (it != null) bases.Add("public virtual " + it);
        }
        if (bases.Count > 0) sb.Append(" : ").Append(string.Join(", ", bases));
        sb.Append(" {\npublic:\n");
        if (isInterface) sb.Append($"    virtual ~{N.FlatName(t)}() = default;\n");

        // fields
        foreach (var f in o.Fields)
            sb.Append($"    {TypeOrGap(f.Type)} {N.Field(f)}{{}};\n");
        foreach (var e in o.Events)
            sb.Append($"    {(e.IsStatic ? "static " : "")}{TypeOrGap(e.Type)} {Names.Ident(e.Name)}{(e.IsStatic ? "" : "{}")};\n");
        foreach (var f in o.StaticFields)
            sb.Append($"    static {TypeOrGap(f.Type)} {N.Field(f)};\n");

        // static initialization: __si() runs the static constructor once
        bool si = tr.StaticInitActive(t);
        bool siGeneric = o.Generic && o.StaticFields.Any(f => NeedsTrace(f.Type));
        if (si || siGeneric)
        {
            sb.Append("    static int8_t cs_cctor_state_;\n");
            sb.Append("    static void __si() {\n        if (cs_cctor_state_) return;\n        cs_cctor_state_ = 1;\n");
            if (siGeneric) sb.Append("        ::cs::RegisterRoots(&cs_trace_statics);\n");
            if (si) sb.Append("        ::cs::StaticScope heap_;\n        __cctor();\n");
            sb.Append("    }\n");
            if (si && !o.Methods.Any(m => m.MethodKind == MethodKind.StaticConstructor)) sb.Append("    static void __cctor();\n");
        }

        // name hiding: overloads of a base's methods stay visible
        var names = new HashSet<string>(StringComparer.Ordinal);
        foreach (var m in o.Methods)
            if (m.MethodKind == MethodKind.Ordinary && !m.IsStatic && t.BaseType != null && N.IsGame(t.BaseType)) names.Add(N.Method(m));
        foreach (var n in names.OrderBy(x => x, StringComparer.Ordinal))
            if (BaseHasMethodNamed(t.BaseType, n)) sb.Append($"    using {N.Type(t.BaseType)}::{n};\n");

        // methods
        foreach (var m in o.Methods)
        {
            var r = tr.Methods[m];
            sb.Append("    ").Append(MethodDecl(m, o, inClass: true)).Append('\n');
        }

        // interface implementations that forward to the C# implementing member
        if (!isInterface) sb.Append(Forwarders(t));

        // runtime support
        if (!isInterface && !isStruct)
        {
            sb.Append($"    const char* cs_typename() const override {{ return \"{Names.FullName(t)}\"; }}\n");
            sb.Append($"    static const char* cs_static_typename() {{ return \"{Names.FullName(t)}\"; }}\n");
            sb.Append("    bool cs_traced() const override { return true; }\n");
            sb.Append("    void cs_trace(::cs::Tracer& t) override;\n");
        }
        if (o.StaticFields.Any(f => NeedsTrace(f.Type)))
            sb.Append("    static void cs_trace_statics(::cs::Tracer& t);\n");
        sb.Append("};\n");
        if (isStruct)
        {
            string cls = N.FlatName(t) + TemplateArgsOf(t);
            sb.Append($"{Template(t)}inline void cs_trace_value(::cs::Tracer& t, const {cls}& v) {{");
            foreach (var f in o.Fields.Where(f => NeedsTrace(f.Type))) sb.Append($" ::cs::TraceField(t, v.{N.Field(f)});");
            sb.Append(" (void)t; (void)v; }\n");
            sb.Append($"{Template(t)}inline const char* cs_box_typename(const {cls}*) {{ return \"{Names.FullName(t)}\"; }}\n");
        }
        return sb.ToString();
    }

    string TemplateArgsOf(INamedTypeSymbol t)
    {
        var tps = Names.AllTypeParameters(t);
        return tps.Count == 0 ? "" : "<" + string.Join(", ", tps.Select(N.TypeParam)) + ">";
    }

    bool BaseHasMethodNamed(INamedTypeSymbol bt, string name)
    {
        for (var b = bt; b != null && N.IsGame(b); b = b.BaseType)
            foreach (var m in b.OriginalDefinition.GetMembers().OfType<IMethodSymbol>())
                if (tr.Methods.ContainsKey(m) && N.Method(m) == name) return true;
        return false;
    }

    static bool NeedsTrace(ITypeSymbol t) => Names.IsRef(t) || t.TypeKind == TypeKind.TypeParameter || t.IsValueType && t.SpecialType == SpecialType.None && t.TypeKind != TypeKind.Enum;

    string TryType(ITypeSymbol t)
    {
        try { return N.Type(t); }
        catch (TranslateException) { return null; }
    }

    string TypeOrGap(ITypeSymbol t)
    {
        try { return N.Ref(t); }
        catch (TranslateException) { return "::cs::Object* /* unmapped: " + t.ToDisplayString() + " */"; }
    }

    string Params(IMethodSymbol m) => string.Join(", ", m.Parameters.Select(p =>
        TypeOrGap(p.Type) + (p.RefKind is RefKind.Ref or RefKind.Out or RefKind.In ? "&" : "") + " " + Body.ParamName(p)));

    string MethodDecl(IMethodSymbol m, TypeOut o, bool inClass)
    {
        var t = o.T;
        string name = N.Method(m);
        string ret = m.MethodKind is MethodKind.Constructor or MethodKind.StaticConstructor ? "void" : TypeOrGap(m.ReturnType);
        string tmpl = m.IsGenericMethod ? "template <" + string.Join(", ", m.TypeParameters.Select(p => "typename " + N.TypeParam(p))) + "> " : "";
        if (m.IsGenericMethod && (m.IsVirtual || m.IsAbstract || m.IsOverride)) tmpl = "/* virtual generic method: not translatable */ " + tmpl;

        // accessors written in the class itself
        if (m.AssociatedSymbol is IPropertySymbol p && tr.IsAutoProperty(p))
        {
            string f = Names.Ident(p.Name);
            string guard = p.IsStatic && tr.StaticInitActive(t) ? "__si(); " : "";
            string virt = AccessorVirtual(m);
            if (m.MethodKind == MethodKind.PropertyGet) return $"{(m.IsStatic ? "static " : virt)}{ret} {name}() {{ {guard}return {f}; }}{Override(m)}";
            return $"{(m.IsStatic ? "static " : virt)}void {name}({TypeOrGap(p.Type)} value) {{ {guard}{f} = value; }}{Override(m)}";
        }
        if (m.AssociatedSymbol is IEventSymbol e && tr.IsFieldLikeEvent(e))
        {
            string dt = N.Type(e.Type);
            string f = Names.Ident(e.Name);
            string op = m.MethodKind == MethodKind.EventAdd ? "Combine" : "Remove";
            return $"{(m.IsStatic ? "static " : AccessorVirtual(m))}void {name}({dt}* value) {{ {f} = {dt}::{op}({f}, value); }}{Override(m)}";
        }
        string mods = "";
        if (m.IsStatic || m.MethodKind == MethodKind.StaticConstructor) mods = "static ";
        else if ((m.IsVirtual || m.IsAbstract || m.IsOverride) && !m.IsGenericMethod) mods = "virtual ";
        else if (t.TypeKind == TypeKind.Interface) mods = "virtual ";
        if (m.MethodKind == MethodKind.ExplicitInterfaceImplementation || m.ExplicitInterfaceImplementations.Length > 0) mods = "virtual ";
        string tail = "";
        if (t.TypeKind == TypeKind.Interface || m.IsAbstract) tail = " = 0";
        string ov = Override(m);
        return $"{tmpl}{mods}{ret} {name}({Params(m)}){ov}{tail};";
    }

    string AccessorVirtual(IMethodSymbol m) => m.IsVirtual || m.IsAbstract || m.IsOverride || m.ExplicitInterfaceImplementations.Length > 0 ? "virtual " : "";

    // `override` when the C++ base declares the method: a translated override, an explicit
    // interface implementation, or System.Object's ToString/Equals/GetHashCode.
    string Override(IMethodSymbol m)
    {
        if (m.ExplicitInterfaceImplementations.Length > 0) return " override";
        if (!m.IsOverride) return "";
        var o = m.OverriddenMethod;
        if (o == null) return "";
        if (N.IsGame(o) && tr.Methods.ContainsKey(o.OriginalDefinition)) return " override";
        var root = o;
        while (root.OverriddenMethod != null) root = root.OverriddenMethod;
        if (root.ContainingType.SpecialType == SpecialType.System_Object && root.Name is "ToString" or "Equals" or "GetHashCode" && !m.ContainingType.IsValueType) return " override";
        return "";
    }

    // Interface members the class maps to an ordinary method: forwarders under the interface's name.
    string Forwarders(INamedTypeSymbol t)
    {
        var sb = new StringBuilder();
        var direct = new HashSet<INamedTypeSymbol>(SymbolEqualityComparer.Default);
        foreach (var i in t.Interfaces)
        {
            direct.Add(i);
            foreach (var ii in i.AllInterfaces) direct.Add(ii);
        }
        var done = new HashSet<string>(StringComparer.Ordinal);
        foreach (var i in direct)
        {
            foreach (var im in i.GetMembers().OfType<IMethodSymbol>())
            {
                if (N.IsGame(im) && !tr.Methods.ContainsKey(im.OriginalDefinition)) continue;
                var impl = t.FindImplementationForInterfaceMember(im) as IMethodSymbol;
                if (impl == null) { sb.Append($"    // no implementation of {im}\n"); continue; }
                if (impl.ExplicitInterfaceImplementations.Any(x => SymbolEqualityComparer.Default.Equals(x.OriginalDefinition, im.OriginalDefinition))
                    && SymbolEqualityComparer.Default.Equals(impl.ContainingType.OriginalDefinition, t.OriginalDefinition)) continue;
                string iname = N.InterfaceMember(im);
                string ret = TypeOrGap(im.ReturnType);
                string ps = string.Join(", ", im.Parameters.Select(p => TypeOrGap(p.Type) + (p.RefKind != RefKind.None ? "&" : "") + " " + Body.ParamName(p)));
                string sig = iname + "(" + ps + ")";
                if (!done.Add(sig)) continue;
                string args = string.Join(", ", im.Parameters.Select(Body.ParamName));
                string target;
                if (!N.IsGame(impl))
                {
                    // implemented by an engine base class: call through it by convention
                    target = $"this->{Names.Ident(impl.Name)}({args})";
                }
                else
                {
                    tr.NeedMethod(impl);
                    target = $"this->{N.Method(impl)}({args})";
                }
                sb.Append($"    {ret} {sig} override {{ {(ret == "void" ? "" : "return ")}{target}; }}\n");
            }
        }
        return sb.ToString();
    }

    // ---- definitions --------------------------------------------------------------------------------------

    void Definitions(TypeOut o, StringBuilder typeSb, StringBuilder templates)
    {
        var t = o.T;
        string tmpl = Template(t);
        // no leading :: : `int32_t ::gen::X::f` would parse as `int32_t::gen...`
        string cls = N.QualifiedGameName(t)[2..] + TemplateArgsOf(t);
        if (t.TypeKind == TypeKind.Interface) return;
        var sb = typeSb;

        // static fields
        foreach (var f in o.StaticFields)
            sb.Append($"{tmpl}{TypeOrGap(f.Type)} {cls}::{N.Field(f)}{{}};\n");
        bool si = tr.StaticInitActive(t);
        bool siGeneric = o.Generic && o.StaticFields.Any(f => NeedsTrace(f.Type));
        if (si || siGeneric) sb.Append($"{tmpl}int8_t {cls}::cs_cctor_state_ = 0;\n");
        if (o.StaticFields.Any(f => NeedsTrace(f.Type)))
        {
            sb.Append($"{tmpl}void {cls}::cs_trace_statics(::cs::Tracer& t) {{");
            foreach (var f in o.StaticFields.Where(f => NeedsTrace(f.Type))) sb.Append($" ::cs::TraceField(t, {N.Field(f)});");
            sb.Append(" }\n");
            if (!o.Generic) sb.Append($"static const bool cs_roots_{N.FlatName(t)} = ::cs::RegisterRoots(&{cls}::cs_trace_statics);\n");
        }
        if (si && !o.Methods.Any(m => m.MethodKind == MethodKind.StaticConstructor))
        {
            // a static constructor made of the static field initializers alone
            sb.Append($"{tmpl}void {cls}::__cctor() {{\n");
            sb.Append(ImplicitCctor(t));
            sb.Append("}\n");
        }

        // cs_trace
        if (t.TypeKind == TypeKind.Class)
        {
            sb.Append($"{tmpl}void {cls}::cs_trace(::cs::Tracer& t) {{\n");
            var bt = t.BaseType;
            if (bt != null && bt.SpecialType != SpecialType.System_Object) sb.Append($"    {N.Type(bt)}::cs_trace(t);\n");
            foreach (var f in o.Fields.Where(f => NeedsTrace(f.Type))) sb.Append($"    ::cs::TraceField(t, this->{N.Field(f)});\n");
            foreach (var e in o.Events.Where(e => !e.IsStatic)) sb.Append($"    ::cs::TraceField(t, this->{Names.Ident(e.Name)});\n");
            sb.Append("    (void)t;\n}\n");
        }
        foreach (var e in o.Events.Where(e => e.IsStatic))
            sb.Append($"{tmpl}{N.Ref(e.Type)} {cls}::{Names.Ident(e.Name)}{{}};\n");

        foreach (var m in o.Methods)
        {
            var r = tr.Methods[m];
            if (m.AssociatedSymbol is IPropertySymbol p && tr.IsAutoProperty(p)) continue;
            if (m.AssociatedSymbol is IEventSymbol e && tr.IsFieldLikeEvent(e)) continue;
            if (m.IsAbstract || t.TypeKind == TypeKind.Interface) continue;
            string name = N.Method(m);
            string ret = m.MethodKind is MethodKind.Constructor or MethodKind.StaticConstructor ? "void" : TypeOrGap(m.ReturnType);
            string mt = m.IsGenericMethod ? "template <" + string.Join(", ", m.TypeParameters.Select(tp => "typename " + N.TypeParam(tp))) + "> " : "";
            // a generic method's definition is a template: in the header, for every user
            var msb = m.IsGenericMethod && !o.Generic ? templates : sb;
            msb.Append($"{tmpl}{mt}{ret} {cls}::{name}({Params(m)}) {{\n");
            if (r.Translated && r.Body != null)
            {
                msb.Append(r.Body);
                r.Lines = r.Body.Count(c => c == '\n');
            }
            else
            {
                string why = r.Error ?? ("missing: " + string.Join("; ", r.Gaps));
                msb.Append($"    // not translated: {why.Replace("\n", " ")}\n");
                msb.Append($"    ::cs::NotTranslated(\"{Names.FullName(t)}::{m.Name}\");\n");
                foreach (var prm in m.Parameters) msb.Append($"    (void){Body.ParamName(prm)};\n");
                if (ret != "void") msb.Append($"    return {DefaultOf(m.ReturnType)};\n");
            }
            msb.Append("}\n");
        }
        sb.Append('\n');
    }

    string DefaultOf(ITypeSymbol t) => Names.IsRef(t) ? "nullptr" : $"{TypeOrGap(t)}{{}}";

    string ImplicitCctor(INamedTypeSymbol t)
    {
        // Translated through a synthesized static constructor symbol when Roslyn has one, else here.
        var cctor = t.StaticConstructors.FirstOrDefault();
        if (cctor != null && tr.Methods.TryGetValue(cctor, out var r) && r.Body != null) return r.Body;
        try
        {
            var mt = new MethodTranslator(tr, cctor ?? throw new TranslateException("no static constructor symbol"));
            return mt.Translate() ?? "";
        }
        catch (TranslateException e)
        {
            return $"    // not translated: {e.Message}\n    ::cs::NotTranslated(\"{Names.FullName(t)}::.cctor\");\n";
        }
    }

    // ---- the report -------------------------------------------------------------------------------------------

    void WriteReport()
    {
        var sb = new StringBuilder("# tools/translate: every translated method. status: ok, error (an unsupported construct), gaps (bindings missing)\n# type\tmethod\tstatus\tdetail\n");
        foreach (var (m, r) in tr.Methods.OrderBy(kv => Names.FullName(kv.Key.ContainingType), StringComparer.Ordinal).ThenBy(kv => kv.Key.Name, StringComparer.Ordinal))
        {
            string status = r.Error != null ? "error" : r.Gaps.Count > 0 ? "gaps" : "ok";
            string detail = r.Error ?? string.Join("; ", r.Gaps);
            sb.Append($"{Names.FullName(m.ContainingType)}\t{m.ToDisplayString(SymbolDisplayFormat.MinimallyQualifiedFormat)}\t{status}\t{detail.Replace('\t', ' ').Replace('\n', ' ')}\n");
        }
        File.WriteAllText(Path.Combine(outDir, "report.tsv"), sb.ToString(), new UTF8Encoding(false));
    }
